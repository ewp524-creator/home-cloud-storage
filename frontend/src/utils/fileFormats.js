export function getExtension(name = '') {
  const cleanName = name.split('/').pop() || ''
  const dotIndex = cleanName.lastIndexOf('.')
  if (dotIndex <= 0 || dotIndex === cleanName.length - 1) return ''
  return cleanName.slice(dotIndex + 1).toLowerCase()
}

export function getFileFormat(file = {}) {
  if (file.kind === 'folder') {
    return {
      ...FORMAT_GROUPS.folder,
      extension: 'FOLDER',
      badge: '文件夹',
    }
  }

  const extension = file.extension?.toLowerCase() || getExtension(file.name)
  const groupName = GROUPS_BY_EXTENSION[extension] || file.format || 'unknown'
  const format = FORMAT_GROUPS[groupName] || FORMAT_GROUPS.unknown

  return {
    ...format,
    extension,
    badge: extension ? extension.toUpperCase().slice(0, 5) : 'FILE',
  }
}

export function getFormatGroups() {
  return FORMAT_GROUPS
}

export function getSupportedExtensions() {
  return Object.keys(GROUPS_BY_EXTENSION)
}

export function getFallbackExtensions(kind) {
  return FALLBACK_EXTENSIONS[kind] || []
}
